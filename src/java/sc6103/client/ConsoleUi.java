package sc6103.client;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.PrintStream;
import java.util.Locale;

import sc6103.common.CodecException;
import sc6103.common.DepartureTime;
import sc6103.common.Protocol;
import sc6103.common.Replies;
import sc6103.common.Requests;
import sc6103.common.StatusCode;

/**
 * The text console of README sec. 7.1, scripted by docs/console-script.md.
 *
 * <p>A numbered menu looping until the user selects quit, one entry per operation. The
 * brief permits a text interface explicitly and says a graphical one is not necessary; a
 * console is also what makes the required request/reply trace legible beside two other
 * machines' logs during the demo.
 *
 * <h2>Two output streams, deliberately not mixed</h2>
 *
 * {@link TraceLog} prints the bracketed protocol trace; this class prints the prose a
 * user reads. They interleave on the same terminal and that is the point - a demo
 * audience watches a retransmission happen next to the sentence it produced - but they
 * are generated by different code with different rules, and nothing here formats a
 * protocol event.
 *
 * <h2>What the client is allowed to say</h2>
 *
 * Error replies carry a status code and <b>no body</b> (D4). Every message a user sees on
 * a failure is therefore composed here, from this client's own request, by
 * {@link StatusText}. The client knows the flight id it asked about; it does not know the
 * server's seat count, its fare, or why it refused. No sentence printed here may imply
 * otherwise.
 */
public final class ConsoleUi {

    private final RequestReply engine;
    private final ClientConfig config;
    private final TraceLog trace;
    private final BufferedReader in;
    private final PrintStream out;

    /**
     * Set when a reply arrives that makes every later request pointless, which today
     * means only {@link StatusCode#ERR_SEMANTICS_MISMATCH}. The menu loop stops rather
     * than re-prompting.
     */
    private boolean sessionUnusable;

    public ConsoleUi(RequestReply engine, ClientConfig config, TraceLog trace,
                     BufferedReader in, PrintStream out) {
        this.engine = engine;
        this.config = config;
        this.trace = trace;
        this.in = in;
        this.out = out;
    }

    /** Runs the menu until the user quits or stdin closes. */
    public void run() throws IOException {
        while (true) {
            printMenu();
            final String choice = prompt("choice");
            if (choice == null) {
                // Stdin closed - a piped demo script ending, or Ctrl-D. Treat it as quit
                // rather than looping on a permanently empty reader.
                out.println();
                printFarewell();
                return;
            }

            switch (choice.trim()) {
                case "1": doQueryByRoute(); break;
                case "2": doQueryById(); break;
                case "3": doReserve(); break;
                case "4": doMonitor(); break;
                case "5": doAdjustFare(); break;
                case "6": doSetFare(); break;
                case "0":
                    printFarewell();
                    return;
                default:
                    // No datagram is sent. Menu selection is a local concern and the
                    // server should never see traffic generated by a typo.
                    out.println("Not an option. Enter 0-6.");
                    out.println();
            }

            if (sessionUnusable) {
                // docs/console-script.md sec. 1: on a semantics mismatch the client
                // exits rather than continuing, because the server will refuse every
                // subsequent request for the same reason. Re-prompting would produce a
                // screen of identical failures and bury the one line that says what to
                // fix.
                printFarewell();
                return;
            }
        }
    }

    // ---- Operations ----

    private void doQueryByRoute() throws IOException {
        final String source = prompt("source");
        final String destination = prompt("destination");
        if (source == null || destination == null) {
            return;
        }

        final Requests.Route body;
        try {
            body = new Requests.Route(source.trim(), destination.trim());
        } catch (IllegalArgumentException e) {
            // Rejected before a datagram is built, so the user retypes instead of
            // spending a round trip to be told no (docs/console-script.md sec. 3).
            out.println(e.getMessage());
            out.println();
            return;
        }

        final RequestReply.Outcome o = engine.call(Protocol.OP_QUERY_BY_ROUTE, body::write);
        final StatusText.Context ctx =
                new StatusText.Context(null, body.source, body.destination);
        if (!completed(o, ctx)) {
            return;
        }

        try {
            final Replies.Route r = Replies.Route.read(o.body);
            out.println();
            out.printf("%d flights, %s to %s%n",
                    r.flightIds.length, body.source, body.destination);
            out.println();
            out.println("  ID");
            for (final int id : r.flightIds) {
                out.printf("  %04d%n", id);
            }
            if (r.truncated) {
                // The flag says matches were omitted, not how many - D14 caps the reply
                // at one datagram rather than paginating, so an exact total is not
                // something the protocol carries.
                out.printf("Showing the first %d matches. More exist.%n",
                        Protocol.MAX_ROUTE_RESULTS);
            }
        } catch (CodecException e) {
            malformedReply(e);
        }
        out.println();
    }

    private void doQueryById() throws IOException {
        final Integer flightId = promptInt("flight id");
        if (flightId == null) {
            return;
        }

        final Requests.Flight body = new Requests.Flight(flightId);
        final RequestReply.Outcome o = engine.call(Protocol.OP_QUERY_BY_ID, body::write);
        final StatusText.Context ctx = new StatusText.Context(flightId, null, null);
        if (!completed(o, ctx)) {
            return;
        }

        try {
            final Replies.Flight r = Replies.Flight.read(o.body);
            final DepartureTime t = r.departure;
            out.println();
            out.printf("Flight %d%n", flightId);
            out.printf("  departure   %04d-%02d-%02d %02d:%02d UTC%n",
                    t.year(), t.month(), t.day(), t.hour(), t.minute());
            out.printf("  fare        %s%n", money(r.airfare));
            out.printf("  seats       %d available%n", r.seatsAvailable);
        } catch (CodecException e) {
            malformedReply(e);
        }
        out.println();
    }

    private void doReserve() throws IOException {
        final Integer flightId = promptInt("flight id");
        if (flightId == null) {
            return;
        }
        final Integer seats = promptInt("seats");
        if (seats == null) {
            return;
        }

        final Requests.Reserve body;
        try {
            body = new Requests.Reserve(flightId, seats);
        } catch (IllegalArgumentException e) {
            out.println("Seats must be at least 1.");
            out.println();
            return;
        }

        final RequestReply.Outcome o = engine.call(Protocol.OP_RESERVE, body::write);
        final StatusText.Context ctx = new StatusText.Context(flightId, null, null);
        if (!completed(o, ctx)) {
            return;
        }

        try {
            final Replies.Reserve r = Replies.Reserve.read(o.body);
            out.println();
            out.printf("Reserved %d seats on flight %d. %d now available.%n",
                    seats, flightId, r.seatsAvailable);
            if (o.transmissions > 1) {
                explainRetryOutcome();
            }
        } catch (CodecException e) {
            malformedReply(e);
        }
        out.println();
    }

    private void doMonitor() throws IOException {
        final Integer flightId = promptInt("flight id");
        if (flightId == null) {
            return;
        }
        final Integer seconds = promptInt("interval (seconds)");
        if (seconds == null) {
            return;
        }

        final Requests.Monitor body;
        try {
            body = new Requests.Monitor(flightId, seconds * 1000);
        } catch (IllegalArgumentException | ArithmeticException e) {
            out.printf("Interval must be between 1 and %d seconds.%n",
                    Requests.Monitor.MAX_INTERVAL_MS / 1000);
            out.println();
            return;
        }

        final RequestReply.Outcome o = engine.call(Protocol.OP_MONITOR, body::write);
        final StatusText.Context ctx = new StatusText.Context(flightId, null, null);
        if (!completed(o, ctx)) {
            return;
        }

        try {
            final Replies.Monitor r = Replies.Monitor.read(o.body);
            out.println();
            // The session times itself from its own monotonic clock. The server's
            // expiresInMs is not passed in as the deadline: it was computed before the
            // reply crossed a lossy link, and D20 makes the local deadline authoritative.
            // One retry timeout of grace lets a MONITOR_END sent at expiry still arrive.
            new MonitorSession(flightId, body.intervalMs, r.seatsAvailable,
                    config.timeoutMs, trace, out).run(engine);
        } catch (CodecException e) {
            malformedReply(e);
            out.println();
        }
    }

    private void doAdjustFare() throws IOException {
        final Integer flightId = promptInt("flight id");
        if (flightId == null) {
            return;
        }
        final Float delta = promptFloat("change by");
        if (delta == null) {
            return;
        }

        final Requests.AdjustFare body;
        try {
            body = new Requests.AdjustFare(flightId, delta);
        } catch (IllegalArgumentException e) {
            out.println(e.getMessage());
            out.println();
            return;
        }

        final RequestReply.Outcome o = engine.call(Protocol.OP_ADJUST_FARE, body::write);
        final StatusText.Context ctx = new StatusText.Context(flightId, null, null);
        if (!completed(o, ctx)) {
            return;
        }

        try {
            final Replies.Fare r = Replies.Fare.read(o.body);
            out.println();
            // Print the delta alongside the result, never the result alone. Under
            // at-least-once with a lost reply this operation runs twice, and a user shown
            // only the final figure has no way to notice - which is exactly the effect
            // experiment E4 is trying to make visible.
            out.printf("Fare for flight %d changed by %s, now %s.%n",
                    flightId, money(delta), money(r.airfare));
            if (o.transmissions > 1) {
                explainRetryOutcome();
            }
        } catch (CodecException e) {
            malformedReply(e);
        }
        out.println();
    }

    private void doSetFare() throws IOException {
        final Integer flightId = promptInt("flight id");
        if (flightId == null) {
            return;
        }
        final Float fare = promptFloat("new fare");
        if (fare == null) {
            return;
        }

        final Requests.SetFare body;
        try {
            body = new Requests.SetFare(flightId, fare);
        } catch (IllegalArgumentException e) {
            out.printf("Fare must be above 0 and at most %s.%n", money(Protocol.MAX_FARE));
            out.println();
            return;
        }

        final RequestReply.Outcome o = engine.call(Protocol.OP_SET_FARE, body::write);
        final StatusText.Context ctx = new StatusText.Context(flightId, null, null);
        if (!completed(o, ctx)) {
            return;
        }

        try {
            final Replies.Fare r = Replies.Fare.read(o.body);
            out.println();
            out.printf("Fare for flight %d is now %s.%n", flightId, money(r.airfare));
            if (o.transmissions > 1) {
                // The idempotency claim, stated where a demo audience can see it. Running
                // the identical request again prints the identical result - that is the
                // whole point of operation 6 and it is worth saying out loud.
                out.println("This operation is idempotent: the repeat wrote the same value.");
            }
        } catch (CodecException e) {
            malformedReply(e);
        }
        out.println();
    }

    // ---- Shared outcome handling ----

    /**
     * Handles the two ways a call can fail to produce a body: no reply at all, and a
     * reply carrying a non-OK status.
     *
     * @return true if the caller should go on to decode a reply body
     */
    private boolean completed(RequestReply.Outcome o, StatusText.Context ctx) {
        if (o.timedOut) {
            out.println();
            out.printf("No reply after %d attempts.%n", o.attempts);
            // The wording is a requirement, not a style choice (README sec. 7.2). A lost
            // request means the operation never ran; a lost reply means it ran and the
            // answer vanished. Nothing available to this client distinguishes them, so it
            // must not say "failed".
            out.println("The server may or may not have executed this request. Query the");
            out.println("flight to find out.");
            out.println();
            return false;
        }

        final int status = o.header.status;
        if (StatusCode.isOk(status)) {
            return true;
        }

        final String message = StatusText.forUser(status, ctx);
        out.println();
        if (status == StatusCode.ERR_SEMANTICS_MISMATCH) {
            // Not merely session-level: unrecoverable. The mode is fixed at startup on
            // both programs (D7), so nothing the user can do from this menu will change
            // the answer.
            sessionUnusable = true;
        }
        if (StatusText.isSessionLevel(status)) {
            // Codes 6-12 are protocol or configuration faults the user cannot fix from a
            // prompt, so they are session-level warnings rather than answers to what was
            // typed (docs/console-script.md sec. 6).
            trace.warn(message);
        } else {
            out.println(message);
        }
        out.println();
        return false;
    }

    /**
     * Says what a reply arriving on a retransmission implies, without overclaiming.
     *
     * <p>Under at-most-once the server answered from its reply history and the operation
     * ran once. Under at-least-once there is no history, so a second arrival was executed
     * again. Both statements are hedged, because the reply could equally be the first
     * attempt's answer arriving late and nothing on the wire separates those cases.
     */
    private void explainRetryOutcome() {
        if (config.semantics == Protocol.SEM_AT_MOST_ONCE) {
            out.println("Answered after a retransmission. Under at-most-once the server");
            out.println("replays its stored reply, so the operation ran once.");
        } else {
            out.println("Answered after a retransmission. Under at-least-once there is no");
            out.println("duplicate filter, so the server may have executed this twice.");
        }
    }

    private void malformedReply(CodecException e) {
        // A reply that passed the header checks and then failed to decode means the two
        // implementations disagree about this operation's body layout - the exact fault
        // the sec. 11.2 conformance vector exists to catch offline. Surface it loudly.
        trace.warn("reply body did not decode: " + e.getMessage());
    }

    // ---- Presentation helpers ----

    /**
     * Formats a fare to two decimals.
     *
     * <p>{@link Locale#ROOT} is not decoration: a European default locale renders this as
     * {@code 899,50}, and the three demo machines would then disagree about what the same
     * float looks like in their captured logs.
     */
    private static String money(float value) {
        return String.format(Locale.ROOT, "%.2f", value);
    }

    private void printMenu() {
        out.println("  1) Find flights by route");
        out.println("  2) Show flight details");
        out.println("  3) Reserve seats");
        out.println("  4) Monitor seat availability");
        out.println("  5) Adjust fare");
        out.println("  6) Set fare");
        out.println("  0) Quit");
        out.println();
    }

    private void printFarewell() {
        out.printf("Closing socket. %d requests sent, %d timed out.%n",
                engine.requestsSent(), engine.timeouts());
    }

    // ---- Input ----

    /** @return the line typed, or null if stdin closed */
    private String prompt(String label) throws IOException {
        out.print(label + "> ");
        out.flush();
        return in.readLine();
    }

    private Integer promptInt(String label) throws IOException {
        final String s = prompt(label);
        if (s == null) {
            return null;
        }
        try {
            return Integer.valueOf(s.trim());
        } catch (NumberFormatException e) {
            out.println("Enter a whole number.");
            out.println();
            return null;
        }
    }

    private Float promptFloat(String label) throws IOException {
        final String s = prompt(label);
        if (s == null) {
            return null;
        }
        try {
            final float v = Float.parseFloat(s.trim());
            if (!Float.isFinite(v)) {
                // Java parses "NaN" and "Infinity" happily. The codec would refuse them
                // (sec. 3.6 step 6), but refusing at the prompt gives a better message
                // than an exception from four layers down.
                out.println("Enter a finite number.");
                out.println();
                return null;
            }
            return Float.valueOf(v);
        } catch (NumberFormatException e) {
            out.println("Enter a number, for example 899.50.");
            out.println();
            return null;
        }
    }
}
